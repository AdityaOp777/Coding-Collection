const numbers = [1, 2, 3, 4, 5];

console.log(numbers);

console.log(numbers[0]); // Accessing the first element

console.log(numbers[numbers.length - 1]); // Accessing the last element

numbers.push(6); // Adding a new element to the end of the array

console.log(numbers);

numbers.pop(); // Removing the last element from the array

console.log(numbers);

numbers.unshift(0); // Adding a new element to the beginning of the array

console.log(numbers);